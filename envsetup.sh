function _get_services() {
  # Dynamically reads all compose layers and returns the list of services (excluding our mcp infrastructure)
  docker compose $DEVBOX_COMPOSE_ARGS config --services 2>/dev/null | grep -v 'mcp'
}

# ==========================================
# --- 🧵 devbox-ps: agent-started processes ---
# ==========================================
# Inspects/manages the background processes the MCP server started inside the
# service containers. devbox-proc.sh is streamed over stdin (it is never
# installed in the containers) and runs there against that container's state
# dir.

# In-container process supervisor, streamed by docker exec's stdin.
_DEVBOX_PROC_SCRIPT="$PROJECT_ROOT/build/devbox-mcp/devbox-proc.sh"

# Run devbox-proc.sh inside a service container, streaming stdout/stderr.
# Usage: _devbox_ps_proc <service> <subcommand> [args...]
function _devbox_ps_proc() {
  local service=${1:-}
  shift
  docker compose $DEVBOX_COMPOSE_ARGS exec -T "$service" sh -s -- "$@" \
    < "$_DEVBOX_PROC_SCRIPT"
}

# Same as _devbox_ps_proc but captures stdout in _DEVBOX_PS_OUT, stderr in
# _DEVBOX_PS_ERR and the exit code in _DEVBOX_PS_RC so callers can map the
# helper's exit codes to friendlier messages.
function _devbox_ps_proc_capture() {
  local service=${1:-}
  shift
  local errfile
  errfile=$(mktemp)
  _DEVBOX_PS_OUT=$(_devbox_ps_proc "$service" "$@" 2>"$errfile")
  _DEVBOX_PS_RC=$?
  _DEVBOX_PS_ERR=$(cat "$errfile" 2>/dev/null)
  rm -f "$errfile"
}

# Running services, minus our MCP infrastructure (mirrors _get_services).
function _devbox_ps_running_services() {
  docker compose $DEVBOX_COMPOSE_ARGS ps --services --status running 2>/dev/null | grep -v 'mcp'
}

# Map a devbox-proc.sh exit code to a user-facing message.
# Usage: _devbox_ps_report_error <service> <id> <rc>
function _devbox_ps_report_error() {
  case "$3" in
    3) echo "❌ Process '$2' not found in '$1'" ;;
    5) echo "❌ setsid is not available in '$1' (cannot run detached processes)" ;;
    *) [ -n "$_DEVBOX_PS_ERR" ] && printf '%s\n' "$_DEVBOX_PS_ERR" ;;
  esac
}

# ^[a-z0-9][a-z0-9-]{0,39}$ — validated on the host before hitting the container.
function _devbox_ps_valid_id() {
  [[ "${1:-}" =~ ^[a-z0-9][a-z0-9-]{0,39}$ ]]
}

# Format one JSON status record (stdin) as running | exited(N) | lost.
function _devbox_ps_format_status() {
  python3 -c '
import json, sys
try:
    o = json.load(sys.stdin)
except Exception:
    o = {}
s = o.get("status") or "?"
if s == "exited":
    ec = o.get("exit_code")
    s = "exited(%s)" % ("?" if ec is None else ec)
print(s)
'
}

function _devbox_ps_usage() {
  echo "❌ Usage: devbox-ps [-a] [service]    (-a: include exited/lost processes)"
  echo "          devbox-ps logs <service> <id> [-f]"
  echo "          devbox-ps stop <service> <id> [grace]"
  echo "          devbox-ps help"
  echo "💡 Services are discovered dynamically and exclude the mcp infrastructure."
  echo "⚠️  A service literally named 'logs', 'stop' or 'help' cannot be listed as"
  echo "   'devbox-ps <service>': the subcommand form takes priority."
}

# Table of agent-started processes across running services (or one service).
function _devbox_ps_table() {
  local ps_args=(ps)
  if [ "${1:-}" = "-a" ]; then
    ps_args+=(-a)
    shift
  fi
  if [ "$#" -gt 1 ] || [[ "${1:-}" == -* ]]; then
    _devbox_ps_usage
    return 1
  fi

  local requested=${1:-}
  local services data="" svc record had_error=0
  if [ -n "$requested" ]; then
    services=$requested
  else
    services=$(_devbox_ps_running_services)
  fi

  if [ -z "$services" ]; then
    echo "ℹ️  No running services to inspect."
    return 0
  fi

  for svc in $services; do
    _devbox_ps_proc_capture "$svc" "${ps_args[@]}"
    if [ "$_DEVBOX_PS_RC" -ne 0 ]; then
      _devbox_ps_report_error "$svc" "" "$_DEVBOX_PS_RC"
      had_error=1
      continue
    fi
    while IFS= read -r record; do
      [ -n "$record" ] || continue
      # Prefix each JSON record with its service; the python formatter reads
      # this from stdin (service data is never interpolated into the source).
      data+="$svc"$'\t'"$record"$'\n'
    done <<< "$_DEVBOX_PS_OUT"
  done

  if [ -z "$data" ]; then
    if [ "$had_error" -eq 0 ]; then
      if [ "${#ps_args[@]}" -gt 1 ]; then
        echo "ℹ️  No processes are being supervised."
      else
        echo "ℹ️  No running processes (use 'devbox-ps -a' to include exited ones)."
      fi
    fi
    return 0
  fi

  printf '%s' "$data" | python3 -c '
import json, sys

rows = []
for raw in sys.stdin:
    raw = raw.rstrip("\n")
    if not raw:
        continue
    svc, _sep, rec = raw.partition("\t")
    try:
        rows.append((svc, json.loads(rec)))
    except Exception:
        continue

def human(u):
    try:
        u = int(u)
    except Exception:
        u = 0
    if u < 0:
        u = 0
    if u < 60:
        return "%ds" % u
    if u < 3600:
        return "%dm%02ds" % (u // 60, u % 60)
    if u < 86400:
        return "%dh%02dm" % (u // 3600, (u % 3600) // 60)
    return "%dd%02dh" % (u // 86400, (u % 86400) // 3600)

def clean(s):
    return " ".join(str(s).split())

def trunc(s, n=60):
    s = clean(s)
    return s if len(s) <= n else s[:n - 3] + "..."

table = []
for svc, o in rows:
    status = o.get("status") or "?"
    if status == "exited":
        ec = o.get("exit_code")
        status = "exited(%s)" % ("?" if ec is None else ec)
    table.append([
        svc,
        str(o.get("id", "")),
        clean(o.get("name", "")),
        status,
        human(o.get("uptime", 0)),
        trunc(o.get("cmd", "")),
    ])

headers = ["SERVICE", "ID", "NAME", "STATUS", "UPTIME", "COMMAND"]
widths = [len(h) for h in headers]
for row in table:
    for i, cell in enumerate(row):
        if len(cell) > widths[i]:
            widths[i] = len(cell)

lines = ["  ".join(h.ljust(widths[i]) for i, h in enumerate(headers)).rstrip()]
for row in table:
    lines.append("  ".join(c.ljust(widths[i]) for i, c in enumerate(row)).rstrip())
sys.stdout.write("\n".join(lines) + "\n")
'
}

# devbox-ps logs <service> <id> [-f]
function _devbox_ps_logs() {
  local service=${1:-}
  local id=${2:-}
  local follow=${3:-}

  if [ -z "$service" ] || [ -z "$id" ] || { [ -n "$follow" ] && [ "$follow" != "-f" ]; }; then
    _devbox_ps_usage
    return 1
  fi
  if ! _devbox_ps_valid_id "$id"; then
    echo "❌ Invalid process id '$id'"
    return 1
  fi

  if [ "$follow" = "-f" ]; then
    _devbox_ps_logs_follow "$service" "$id"
    return $?
  fi

  local tmp err rc
  tmp=$(mktemp)
  err=$(mktemp)
  # tail_lines=200, no offset: the log content follows the JSON header line.
  docker compose $DEVBOX_COMPOSE_ARGS exec -T "$service" sh -s -- logs "$id" 200 \
    < "$_DEVBOX_PROC_SCRIPT" > "$tmp" 2> "$err"
  rc=$?
  if [ "$rc" -ne 0 ]; then
    _DEVBOX_PS_ERR=$(cat "$err" 2>/dev/null)
    _devbox_ps_report_error "$service" "$id" "$rc"
    rm -f "$tmp" "$err"
    return 1
  fi
  # Drop the JSON header line, keep the raw log bytes.
  tail -n +2 "$tmp"
  rm -f "$tmp" "$err"
}

# Follow a process log: poll logs with an advancing absolute offset once a second.
function _devbox_ps_logs_follow() {
  local service=${1:-}
  local id=${2:-}
  local old_int offset= status= header= tmp err rc interrupted=0

  old_int=$(trap -p INT)
  # Use a flag instead of returning from the handler so the previous INT trap
  # can be restored on every exit path.
  trap 'interrupted=1' INT

  while :; do
    [ "$interrupted" -eq 1 ] && break

    tmp=$(mktemp)
    err=$(mktemp)
    # First read shows the last 200 lines (like tail -f), then follow by offset.
    if [ -z "$offset" ]; then
      set -- logs "$id" 200
    else
      set -- logs "$id" 0 "$offset"
    fi
    docker compose $DEVBOX_COMPOSE_ARGS exec -T "$service" sh -s -- "$@" \
      < "$_DEVBOX_PROC_SCRIPT" > "$tmp" 2> "$err"
    rc=$?
    if [ "$rc" -ne 0 ]; then
      _DEVBOX_PS_ERR=$(cat "$err" 2>/dev/null)
      _devbox_ps_report_error "$service" "$id" "$rc"
      rm -f "$tmp" "$err"
      break
    fi

    header=$(head -n 1 "$tmp")
    tail -n +2 "$tmp"

    if [ -n "$header" ]; then
      read -r offset status < <(printf '%s' "$header" | python3 -c '
import json, sys
try:
    d = json.load(sys.stdin)
except Exception:
    d = {}
sys.stdout.write("%s %s\n" % (d.get("next_offset", 0), d.get("status", "")))
')
    fi
    rm -f "$tmp" "$err"

    case "$status" in
      exited|lost)
        echo "⌛ Process '$id' is $status."
        break
        ;;
    esac
    [ "$interrupted" -eq 1 ] && break
    sleep 1
  done

  if [ "$interrupted" -eq 1 ]; then
    echo "👋 Stopped following '$id'."
  fi
  # Restore whatever INT trap was in place before.
  if [ -n "$old_int" ]; then
    eval "$old_int"
  else
    trap - INT
  fi
}

# devbox-ps stop <service> <id> [grace]
function _devbox_ps_stop() {
  local service=${1:-}
  local id=${2:-}
  local grace=${3:-10}

  if [ -z "$service" ] || [ -z "$id" ]; then
    _devbox_ps_usage
    return 1
  fi
  if ! _devbox_ps_valid_id "$id"; then
    echo "❌ Invalid process id '$id'"
    return 1
  fi
  if ! [[ "$grace" =~ ^[0-9]+$ ]]; then
    echo "❌ Invalid grace '$grace' (expected a whole number of seconds)"
    return 1
  fi

  _devbox_ps_proc_capture "$service" stop "$id" "$grace"
  if [ "$_DEVBOX_PS_RC" -ne 0 ]; then
    _devbox_ps_report_error "$service" "$id" "$_DEVBOX_PS_RC"
    return 1
  fi

  local status
  status=$(printf '%s' "$_DEVBOX_PS_OUT" | _devbox_ps_format_status)
  echo "✅ Process '$id' in '$service' is now: $status"
}

function devbox-ps() {
  # NOTE: the subcommand forms take priority over a service of the same name.
  case "${1:-}" in
    logs)
      shift
      _devbox_ps_logs "$@"
      ;;
    stop)
      shift
      _devbox_ps_stop "$@"
      ;;
    help|--help|-h)
      _devbox_ps_usage
      return 0
      ;;
    *)
      _devbox_ps_table "$@"
      ;;
  esac
}

function devbox-run() {
  local service=$1
  shift # Remove the first argument so the rest is just the command

  if [ -z "$service" ] || [ -z "$1" ]; then
    echo "❌ Usage: devbox-run <service> <command>"
    echo "💡 Available services: $(_get_services | paste -sd ', ' -)"
    return 1
  fi

  echo "🚀 Running '$*' in '$service'..."
  docker compose $DEVBOX_COMPOSE_ARGS exec "$service" "$@"
}

function devbox-edit() {
  local service=$1

  if [ -z "$service" ]; then
    echo "❌ Usage: devbox-edit <service>"
    echo "💡 Available services: $(_get_services | paste -sd ', ' -)"
    return 1
  fi

  echo "💻 Launching IDE in '$service'..."
  docker compose $DEVBOX_COMPOSE_ARGS exec "$service" nvim .
}

