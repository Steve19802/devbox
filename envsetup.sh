#!/bin/bash

# Get the directory where envsetup.sh is located, then go up one level to the project root
PROJECT_ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)

# ---- Project config (devbox.json) loading ----
# Remember the compose override the user brought in the environment ONCE, before
# any value derived from devbox.json is applied. Reloading must not mistake a
# value we computed from devbox.json earlier for a user-provided one, so the
# fallback below always consults this snapshot instead of $DEVBOX_COMPOSE_ARGS.
_DEVBOX_USER_COMPOSE_ARGS="${DEVBOX_COMPOSE_ARGS-}"

# Internal helper: (re)load devbox.json into DEVBOX_MCP_* and the compose args.
# It is called once at source time and again at the start of devbox-up /
# devbox-rebuild, so edits to devbox.json (or a file just generated by
# devbox-init) take effect without re-sourcing this script.
#
# Precedence for the compose files (highest first):
#   devbox.json compose_files  >  pre-existing environment value  >  default
function _devbox_load_config() {
  # Clear any MCP settings inherited from a previously sourced environment or an
  # earlier load so that only values actually present in devbox.json are exported.
  unset DEVBOX_MCP_PROTECTED_SERVICES DEVBOX_MCP_DEFAULT_TIMEOUT \
        DEVBOX_MCP_MAX_TIMEOUT DEVBOX_MCP_MAX_OUTPUT_KB \
        DEVBOX_MCP_MAX_PROCS DEVBOX_MCP_MAX_LOG_MB
  # Reset before the python snippet (re)emits it from scratch each load.
  _COMPOSE_FILES=""

  _DEVBOX_CONFIG="$PROJECT_ROOT/devbox.json"
  if [ -f "$_DEVBOX_CONFIG" ]; then
    # Read compose_files and the optional mcp section from devbox.json. The
    # snippet prints shlex-quoted shell assignments which we eval; the config
    # path and project root are passed as argv (not interpolated into the Python
    # source) so paths with quotes/spaces cannot break the generated code.
    eval "$(python3 -c '
import json, shlex, sys

config_path, project_root = sys.argv[1], sys.argv[2]

def emit(name, value, export=False):
    prefix = "export " if export else ""
    sys.stdout.write(prefix + name + "=" + shlex.quote(str(value)) + chr(10))

try:
    with open(config_path) as f:
        cfg = json.load(f)
except Exception as e:
    sys.stderr.write("devbox: failed to parse devbox.json: " + str(e) + chr(10))
    sys.exit(0)

files = cfg.get("compose_files", [])
emit("_COMPOSE_FILES", " ".join("-f " + project_root + "/" + str(f) for f in files))

mcp = cfg.get("mcp") or {}
mcp_exec = mcp.get("exec") or {}
mcp_procs = mcp.get("processes") or {}

if "protected_services" in mcp:
    services = mcp["protected_services"]
    if isinstance(services, list):
        services = ",".join(str(s) for s in services)
    emit("DEVBOX_MCP_PROTECTED_SERVICES", services, export=True)
if "default_timeout" in mcp_exec:
    emit("DEVBOX_MCP_DEFAULT_TIMEOUT", mcp_exec["default_timeout"], export=True)
if "max_timeout" in mcp_exec:
    emit("DEVBOX_MCP_MAX_TIMEOUT", mcp_exec["max_timeout"], export=True)
if "max_output_kb" in mcp_exec:
    emit("DEVBOX_MCP_MAX_OUTPUT_KB", mcp_exec["max_output_kb"], export=True)
if "max_per_container" in mcp_procs:
    emit("DEVBOX_MCP_MAX_PROCS", mcp_procs["max_per_container"], export=True)
if "max_log_mb" in mcp_procs:
    emit("DEVBOX_MCP_MAX_LOG_MB", mcp_procs["max_log_mb"], export=True)
' "$_DEVBOX_CONFIG" "$PROJECT_ROOT")"
  fi

  # Define the 3-layer compose files — overridable via devbox.json or environment
  if [ -n "$_COMPOSE_FILES" ]; then
    DEVBOX_COMPOSE_ARGS="$_COMPOSE_FILES"
  elif [ -n "$_DEVBOX_USER_COMPOSE_ARGS" ]; then
    DEVBOX_COMPOSE_ARGS="$_DEVBOX_USER_COMPOSE_ARGS"
  else
    DEVBOX_COMPOSE_ARGS="-f $PROJECT_ROOT/docker-compose.yml -f $PROJECT_ROOT/docker-compose.dev.yml -f $PROJECT_ROOT/build/docker-compose.mcp.yml"
  fi
}

_devbox_load_config

# Dynamically fetch the host's actual UID/GID to prevent permission issues
LOCAL_UID=$(id -u 2>/dev/null || echo 1000)
LOCAL_GID=$(id -g 2>/dev/null || echo 1000)

# Exported for docker-compose files that use "${DEVBOX_UID:-1000}:${DEVBOX_GID:-1000}"
# (e.g. the dev override generated by 'devbox-adopt').
export DEVBOX_UID="$LOCAL_UID"
export DEVBOX_GID="$LOCAL_GID"

# Internal helper: runs a Python script from build/scripts/ inside a Docker container
function _devbox_run_python() {
  local script=$1
  shift
  # Smart TTY detection: use -it when user is interactive, -i for CI/pipes
  local tty_flag="-i"
  if [ -t 0 ]; then
    tty_flag="-it"
  fi
  docker run --rm $tty_flag \
    -u "$LOCAL_UID:$LOCAL_GID" \
    -v "$PROJECT_ROOT:/workspace" \
    -w /workspace \
    -e LOCAL_UID="$LOCAL_UID" \
    -e LOCAL_GID="$LOCAL_GID" \
    python:3.11-slim \
    python "/workspace/build/scripts/$script" "$@"
}

# --- Run Python script natively (no Docker) for adopt/local operations ---
function _devbox_run_python_native() {
  local script=$1
  shift
  python3 "$PROJECT_ROOT/build/scripts/$script" "$@"
}

function devbox-ai-setup() {
  echo "🤖 Configuring AI toolchain..."
  _devbox_run_python ai_setup.py "$@"
}
# --- Docker Compose Helpers (V2) ---

function devbox-up() {
  # Pick up edits to devbox.json (or a fresh one from devbox-init) without re-sourcing.
  _devbox_load_config
  echo "🚀 Starting DevBox..."
  # The "$@" allows you to pass flags like --remove-orphans, --force-recreate, or -d
  docker compose $DEVBOX_COMPOSE_ARGS up "$@"
}

function devbox-build() {
  echo "🧱 Building DevBox infrastructure..."
  # The "$@" passes any extra flags directly to the build command
  docker compose $DEVBOX_COMPOSE_ARGS build "$@"
}

function devbox-down() {
  echo "🛑 Stopping development environment..."
  docker compose $DEVBOX_COMPOSE_ARGS down "$@"
}

function devbox-rebuild() {
  # Pick up edits to devbox.json (or a fresh one from devbox-init) without re-sourcing.
  _devbox_load_config
  echo "♻️  Rebuilding DevBox and renewing anonymous volumes..."
  # Anonymous volumes (e.g. node_modules) are reused across container recreation,
  # so dependency changes require renewing them to avoid stale packages.
  docker compose $DEVBOX_COMPOSE_ARGS down
  docker compose $DEVBOX_COMPOSE_ARGS build
  docker compose $DEVBOX_COMPOSE_ARGS up --renew-anon-volumes "$@"
}

function devbox-logs() {
  # If no argument is passed, show all logs. Otherwise, show logs for the specific service.
  if [ -z "$1" ]; then
    echo "📜 Tailing logs for all services (Press CTRL+C to exit)..."
    docker compose $DEVBOX_COMPOSE_ARGS logs -f
  else
    echo "📜 Tailing logs for $1 (Press CTRL+C to exit)..."
    docker compose $DEVBOX_COMPOSE_ARGS logs -f "$1"
  fi
}

